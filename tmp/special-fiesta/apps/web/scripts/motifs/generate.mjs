#!/usr/bin/env node
/**
 * ADR-014 / ADR-067 / ADR-297 — writes the decorative motif sprites used by the participant
 * theme (fds.md §5.5 "Gameboy/Pokémon"), once per venue theme. The art is in `core.mjs`,
 * `grids/` and `scripts/themes/<id>/`; this file is only I/O.
 *
 * Same rules as the avatars (ADR-008): pixel art, deterministic, committed output, referenced
 * by URL and never drawn at runtime. Decoration is participant-only — facilitator and
 * superadmin surfaces stay text-only, and `npm run standards` fails if anything under
 * components/participant/ is imported there.
 *
 * For each theme in `scripts/themes/` (or only `--theme <id>`):
 *   public/themes/<id>/motifs/*.svg          the sprites, in that theme's palette
 *   src/themes/<id>/art/motifVersion.ts      the content stamp (ADR-067)
 *   <manifest.stylesheets>                   the `?v=` stamps on every sprite URL they name
 *
 *   npm run motifs --workspace @psd/web
 */
import { existsSync } from 'node:fs';
import { mkdir, readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { buildSprites, versionOf } from './core.mjs';
import { corpusFor } from './theme-corpus.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const THEMES_DIR = join(ROOT, 'scripts', 'themes');

const escapeForRegExp = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** Matches `/themes/<id>/motifs/<name>.svg` with or without a stamp; group 1 is the name. */
function referencePattern(id) {
  return new RegExp(`/themes/${escapeForRegExp(id)}/motifs/([a-z0-9-]+)\\.svg(\\?v=[0-9a-f]+)?`, 'g');
}

function versionModule(version) {
  return [
    '/**',
    ' * Generated by scripts/motifs/generate.mjs — do not edit by hand.',
    ' *',
    ' * Content hash of the emitted sprites (ADR-014, ADR-067). It is appended to every sprite',
    ' * URL so a redrawn motif can never be served from a stale cache under its old name.',
    ' */',
    '',
    `export const MOTIF_VERSION = '${version}';`,
    '',
  ].join('\n');
}

/**
 * A stylesheet names sprites directly, so the stamp has to reach it too.
 *
 * ADR-067 — the old pattern was `([a-z]+)`, which silently skipped any name containing a digit
 * or a hyphen *and still reported success*, reintroducing the very stale-cache bug ADR-018
 * exists to fix. Widening the charset is not enough on its own, so the result is checked.
 */
function stampStylesheet({ id, path, current, version, names }) {
  const pattern = referencePattern(id);
  const stamped = current.replace(
    pattern,
    (_match, name) => `/themes/${id}/motifs/${name}.svg?v=${version}`,
  );

  const stale = [...stamped.matchAll(/\/motifs\/[a-z0-9-]+\.svg\?v=([0-9a-f]+)/g)]
    .map((match) => match[1])
    .filter((found) => found !== version);
  if (stale.length > 0) {
    throw new Error(`${path} kept stale sprite stamps: ${[...new Set(stale)].join(', ')}`);
  }

  const referenced = [...stamped.matchAll(pattern)].map((match) => match[1]);
  const missing = referenced.filter((name) => !names.includes(name));
  if (missing.length > 0) {
    throw new Error(`${path} references sprites that are not generated: ${missing.join(', ')}`);
  }

  return { stamped, referenced: [...new Set(referenced)] };
}

/**
 * A tiled sprite's CSS tile size and its grid are coupled, and nothing has ever checked them.
 * Reported rather than thrown for now: `wave` ships at 20x10 and 24x12 from a 16x8 grid, both
 * fractional. This becomes an error when `wave` moves to a 20x10 grid.
 */
function reportTileScale(id, css, grids) {
  const pattern = new RegExp(
    `url\\('/themes/${escapeForRegExp(id)}/motifs/([a-z0-9-]+)\\.svg[^']*'\\)[^;]*?/\\s*(\\d+)px\\s+(\\d+)px`,
    'g',
  );
  for (const [, name, width, height] of css.matchAll(pattern)) {
    const rows = grids[name];
    if (!rows) continue;
    // Row length is characters, not pixels — a four-tone grid spends two characters per cell.
    const gridWidth = rows[0].length / 2;
    const gridHeight = rows.length;
    const scale = Number(width) / gridWidth;
    if (scale !== Number(height) / gridHeight || !Number.isInteger(scale)) {
      console.warn(
        `  warn ${name}: CSS tile ${width}x${height} is ${scale}x its ${gridWidth}x${gridHeight} grid`,
      );
    }
  }
}

/** Sprites no longer in the corpus must not linger — a stale file is a silent 404 waiting. */
async function removeRetired(outDir, names) {
  const present = (await readdir(outDir)).filter((file) => file.endsWith('.svg'));
  const retired = present.filter((file) => !names.includes(file.replace(/\.svg$/, '')));
  for (const file of retired) await unlink(join(outDir, file));
  return retired;
}

async function loadManifest(id) {
  const url = pathToFileURL(join(THEMES_DIR, id, 'manifest.mjs')).href;
  const { MANIFEST } = await import(url);
  if (MANIFEST.id !== id) throw new Error(`${id}/manifest.mjs declares id "${MANIFEST.id}"`);
  return MANIFEST;
}

/**
 * Build and validate everything before writing anything. The previous version wrote inside its
 * loop, so a throw on the twelfth sprite left eleven new files beside a stale version module
 * and a stale stylesheet — a working tree that looks generated but is not.
 */
async function generateTheme(id) {
  const manifest = await loadManifest(id);
  const corpus = corpusFor(manifest);
  const sprites = buildSprites(corpus);
  const names = Object.keys(sprites);
  const version = versionOf(sprites);

  const sheets = await Promise.all(
    manifest.stylesheets.map(async (relative) => {
      const path = join(ROOT, relative);
      const current = await readFile(path, 'utf8');
      return { path, relative, current, ...stampStylesheet({ id, path: relative, current, version, names }) };
    }),
  );

  const outDir = join(ROOT, 'public', 'themes', id, 'motifs');
  const versionPath = join(ROOT, 'src', 'themes', id, 'art', 'motifVersion.ts');
  await mkdir(outDir, { recursive: true });
  await mkdir(dirname(versionPath), { recursive: true });
  for (const name of names) await writeFile(join(outDir, `${name}.svg`), sprites[name], 'utf8');
  await writeFile(versionPath, versionModule(version), 'utf8');
  for (const sheet of sheets) {
    if (sheet.stamped !== sheet.current) await writeFile(sheet.path, sheet.stamped, 'utf8');
    reportTileScale(id, sheet.stamped, corpus.grids);
  }
  const retired = await removeRetired(outDir, names);

  console.log(`${id}: wrote ${names.length} motifs to public/themes/${id}/motifs (version ${version})`);
  for (const sheet of sheets) {
    console.log(`  ${sheet.referenced.length} referenced from ${sheet.relative}: ${sheet.referenced.join(', ')}`);
  }
  if (retired.length > 0) console.log(`  removed retired: ${retired.join(', ')}`);
}

async function themeIds() {
  const flag = process.argv.indexOf('--theme');
  if (flag !== -1) {
    const id = process.argv[flag + 1];
    if (!id) throw new Error('--theme needs an id');
    return [id];
  }
  const entries = await readdir(THEMES_DIR, { withFileTypes: true });
  // A theme is a directory WITH a manifest. A half-made one (an empty folder, a venue whose art is
  // still being drawn) is skipped rather than crashing the whole build.
  return entries
    .filter((entry) => entry.isDirectory() && existsSync(join(THEMES_DIR, entry.name, 'manifest.mjs')))
    .map((entry) => entry.name)
    .sort();
}

async function main() {
  for (const id of await themeIds()) await generateTheme(id);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
