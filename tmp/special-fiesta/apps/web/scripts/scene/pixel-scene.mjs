/**
 * ADR-298 — building a venue's pixel scene, with nothing in it that is Sentosa.
 *
 * Given a venue's `SCENE` (its id, plate size, layer composition and player timings) this
 * renders the classic (1 px per art unit) and fine (2 px) variants, hashes them, and produces the
 * bytes to write: the PNG layers and the generated TypeScript art module. It does no I/O itself,
 * so the review sheet and the CLI both use it, and a test can build a made-up venue.
 *
 * It used to be one file that imported Sentosa's drawing code directly, which is why
 * `npm run scene` could only ever build Sentosa.
 */
import { createHash } from 'node:crypto';

import { encodePng } from '../pixel-canvas.mjs';

/** The two variants every venue emits. `dir` is relative to `public/themes/<id>/`. */
export const VARIANTS = [
  { name: 'classic', scale: 1, dir: 'scene' },
  { name: 'fine', scale: 2, dir: 'scene-2x' },
];

/** Renders one variant: its layers (encoded), the geometry, and a content hash of the bytes. */
export function buildScene(scene, scale = 1) {
  const variant = scene.compose(scale);
  const encoded = variant.layers.map(([name, canvas]) => [name, encodePng(canvas)]);
  const hash = createHash('sha1');
  for (const [name, bytes] of encoded) hash.update(name).update(bytes);
  return { ...variant, encoded, version: hash.digest('hex').slice(0, 8) };
}

/** Renders both variants and the combined stamp that goes on every URL. */
export function buildAll(scene) {
  const built = VARIANTS.map((variant) => ({ ...variant, scene: buildScene(scene, variant.scale) }));
  const stamp = createHash('sha1');
  for (const { scene: variant } of built) stamp.update(variant.version);
  return { built, version: stamp.digest('hex').slice(0, 8) };
}

function serialiseParts(constant, urlDir, geometry, version) {
  const entries = Object.entries(geometry).map(([name, style]) => {
    const fields = Object.entries(style)
      .map(([key, value]) => `${key}: '${value}'`)
      .join(', ');
    return `  ${name}: { src: '/${urlDir}/${name}.png?v=${version}', style: { ${fields} } },`;
  });
  return [`export const ${constant} = {`, ...entries, '} as const;', ''];
}

/** The generated `art/pixelArt.ts` for one venue. */
export function serialise(scene, geometry, version) {
  const { width, height } = scene.size;
  const [classic, fine] = VARIANTS;
  return [
    '/* GENERATED by apps/web/scripts/scene/generate-pixel.mjs — do not edit. */',
    '/* Run `npm run scene --workspace @psd/web` after changing the scene art. */',
    '',
    `export const SCENE_VERSION = '${version}';`,
    '',
    '/** Art-space size of the backdrop; the scene box keeps this ratio at every width. */',
    `export const SCENE_SIZE = { width: ${width}, height: ${height} } as const;`,
    '',
    '/**',
    ' * One entry per layer, with the finished style: sizes and offsets are percentages of',
    ' * the scene box, so a sprite stays glued to its pixel of the panorama at any scale.',
    ` * <${scene.componentName}> only spreads these — the geometry lives here, next to the art.`,
    ' */',
    ...serialiseParts('SCENE_PARTS', `themes/${scene.id}/${classic.dir}`, geometry, version),
    '/** ADR-023 — the same scene drawn at two pixels per art unit, for the A/B comparison. */',
    ...serialiseParts('SCENE_PARTS_FINE', `themes/${scene.id}/${fine.dir}`, geometry, version),
    '/** Flip period per player, so four figures never move as one. */',
    `export const PLAYER_PERIODS = [${scene.playerPeriods.map((period) => `'${period}'`).join(', ')}] as const;`,
    '',
  ].join('\n');
}
