#!/usr/bin/env node
/**
 * ADR-235 — draw the demo nicknames from the name pools, once, with a fixed seed.
 *
 *   node scripts/draw-demo-names.mjs          dry run: prints what would change, writes nothing
 *   node scripts/draw-demo-names.mjs --write  writes the files listed below
 *
 * Inputs: the lookup table (docs/design/demo-identities-worksheet.csv), which holds each photo's
 * ethnicity label and where the label came from (ADR-236), and the pools in
 * scripts/demo-name-pools.json. A photo labelled Chinese, Malay, Indian or Eurasian takes a
 * nickname from the pool for that label and the persona's gender. Any other label, or none, keeps
 * the nickname it has: the pools have no group for it, so nothing is guessed.
 *
 * Every nickname must follow the contract's rule (3 to 20 characters, letters and underscores, not
 * all digits) and be unique across all participants, case-insensitively. The seed is fixed, so the
 * same inputs give the same names.
 *
 * With --write it changes only: the nickname field in scripts/demo-personas.json, the nickname
 * column of the lookup table, and the nickname cells of the Personas table in
 * docs/design/synthetic-social-photos.md. It does not touch the recorded dump or seed-demo.sql:
 * those are regenerated by the real-model recording (ADR-226, reserved).
 */
import fs from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SEED = 20261009;
const WRITE = process.argv.includes('--write');
const DRAWN_LABELS = new Set(['Chinese', 'Malay', 'Indian', 'Eurasian']);
const RULE = /^[A-Za-z_]+$/;
const DOC_SENTENCE_OLD =
  'The 80 earlier personas are not listed here, and their names are unchanged.';
const DOC_SENTENCE_NEW =
  'The 80 earlier personas are not listed here. Their nicknames were drawn under ADR-235 from the ' +
  "lookup table's labels, except the top-level 20 and the six photos labelled Eurasian / Other or " +
  'Uncertain, which keep theirs. Their labels and where they came from are in ' +
  '`docs/design/demo-identities-worksheet.csv` (ADR-236).';

const path = (...parts) => join(ROOT, ...parts);

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') {
        field += '"';
        i += 1;
      } else if (ch === '"') {
        quoted = false;
      } else {
        field += ch;
      }
    } else if (ch === '"') {
      quoted = true;
    } else if (ch === ',') {
      row.push(field);
      field = '';
    } else if (ch === '\n') {
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
    } else if (ch !== '\r') {
      field += ch;
    }
  }
  if (field !== '' || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

const csvField = (value) => (/[",\n]/.test(value) ? `"${value.replace(/"/g, '""')}"` : value);

function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function fail(message) {
  console.error(`[draw-demo-names] ${message}`);
  process.exit(1);
}

// --- inputs -----------------------------------------------------------------------------------
const personasText = fs.readFileSync(path('scripts', 'demo-personas.json'), 'utf8');
const personasFile = JSON.parse(personasText);
if (JSON.stringify(personasFile, null, 1) !== personasText) {
  fail('demo-personas.json is not in the one-space format this script writes; stop and look');
}
const personas = personasFile.participants;
const pools = JSON.parse(fs.readFileSync(path('scripts', 'demo-name-pools.json'), 'utf8')).pools;
const lookupPath = path('docs', 'design', 'demo-identities-worksheet.csv');
const [header, ...lookup] = parseCsv(fs.readFileSync(lookupPath, 'utf8').trim());
const col = Object.fromEntries(header.map((name, index) => [name, index]));
for (const name of ['sourceImage', 'nickname', 'gender', 'ethnicity']) {
  if (col[name] === undefined) fail(`lookup table has no ${name} column`);
}

const personaBySource = new Map(personas.map((p) => [p.sourceImage, p]));
for (const row of lookup) {
  const persona = personaBySource.get(row[col.sourceImage]);
  if (!persona) fail(`lookup row has no persona: ${row[col.sourceImage]}`);
  if (persona.nickname !== row[col.nickname]) fail(`lookup nickname differs from personas: ${row[col.sourceImage]}`);
  if (persona.gender !== row[col.gender]) fail(`lookup gender differs from personas: ${row[col.sourceImage]}`);
}

// --- draw -------------------------------------------------------------------------------------
// Nicknames that are kept are reserved first, so a drawn name can never duplicate one of them.
const used = new Set();
for (const row of lookup) {
  if (!DRAWN_LABELS.has(row[col.ethnicity])) used.add(row[col.nickname].toLowerCase());
}
const random = mulberry32(SEED);
const pick = (list) => list[Math.floor(random() * list.length)];
const drawn = new Map(); // sourceImage -> new nickname
const perGroup = {};
let rejected = 0;
for (const row of lookup) {
  const label = row[col.ethnicity];
  if (!DRAWN_LABELS.has(label)) continue;
  const gender = row[col.gender];
  const pool = pools[label]?.[gender];
  if (!pool) fail(`no pool for ${label} ${gender}`);
  let nickname = null;
  for (let attempt = 0; attempt < 10000 && nickname === null; attempt += 1) {
    const candidate = `${pick(pool.first)}_${pick(pool.last)}`;
    if (candidate.length < 3 || candidate.length > 20 || used.has(candidate.toLowerCase())) {
      rejected += 1;
      continue;
    }
    nickname = candidate;
  }
  if (nickname === null) fail(`no free nickname for ${row[col.sourceImage]}`);
  used.add(nickname.toLowerCase());
  drawn.set(row[col.sourceImage], nickname);
  const key = `${label} ${gender}`;
  perGroup[key] = (perGroup[key] ?? 0) + 1;
}

// --- checks -----------------------------------------------------------------------------------
const next = personas.map((p) => ({ ...p, nickname: drawn.get(p.sourceImage) ?? p.nickname }));
const seen = new Set();
for (const p of next) {
  const n = p.nickname;
  if (n.length < 3 || n.length > 20 || !RULE.test(n)) fail(`breaks the nickname rule: ${n}`);
  if (seen.has(n.toLowerCase())) fail(`duplicate nickname: ${n}`);
  seen.add(n.toLowerCase());
}
const changed = next.filter((p, i) => p.nickname !== personas[i].nickname).length;
const kept = next.length - drawn.size;
console.log(`personas: ${next.length} | drawn: ${drawn.size} | nicknames that changed: ${changed} | kept: ${kept} | rejected candidates: ${rejected}`);
console.log(`drawn per group: ${JSON.stringify(perGroup)}`);
console.log('all nicknames unique (case-insensitive) and within the rule: true');

// The Personas table in the design doc lists photos 61 to 100 by number.
const docPath = path('docs', 'design', 'synthetic-social-photos.md');
const docText = fs.readFileSync(docPath, 'utf8');
const newByNumber = new Map();
for (const [source, nickname] of drawn) {
  const m = source.match(/ingest\/social\/(\d+)-/);
  if (m) newByNumber.set(Number(m[1]), nickname);
}
const oldByNumber = new Map();
for (const p of personas) {
  const m = p.sourceImage.match(/ingest\/social\/(\d+)-/);
  if (m) oldByNumber.set(Number(m[1]), p.nickname);
}
let docRows = 0;
const docLines = docText.split('\n').map((line) => {
  const m = line.match(/^\| (\d{2,3}) \| ([A-Za-z_]+) \| /);
  if (!m) return line;
  const number = Number(m[1]);
  if (number < 61 || number > 100) return line;
  if (m[2] !== oldByNumber.get(number)) fail(`design doc row ${number} does not match the personas file`);
  const replacement = newByNumber.get(number);
  if (!replacement) fail(`no new nickname for design doc row ${number}`);
  docRows += 1;
  return line.replace(`| ${m[2]} |`, `| ${replacement} |`);
});
if (docRows !== 40) fail(`expected 40 Personas rows in the design doc, found ${docRows}`);
let newDoc = docLines.join('\n');
// A run after --write finds the new sentence already in place, and that is not an error.
if (newDoc.split(DOC_SENTENCE_OLD).length === 2) {
  newDoc = newDoc.replace(DOC_SENTENCE_OLD, DOC_SENTENCE_NEW);
} else if (!newDoc.includes(DOC_SENTENCE_NEW)) {
  fail('design doc sentence not found exactly once');
}
console.log(`design doc: ${docRows} Personas rows updated`);

if (!WRITE) {
  console.log('dry run: nothing written. Re-run with --write to apply.');
  process.exit(0);
}

// --- write ------------------------------------------------------------------------------------
fs.writeFileSync(path('scripts', 'demo-personas.json'), JSON.stringify({ ...personasFile, participants: next }, null, 1));
const lookupOut = [header, ...lookup.map((row) => {
  const copy = [...row];
  if (drawn.has(row[col.sourceImage])) copy[col.nickname] = drawn.get(row[col.sourceImage]);
  return copy;
})];
fs.writeFileSync(lookupPath, lookupOut.map((row) => row.map(csvField).join(',')).join('\n') + '\n');
fs.writeFileSync(docPath, newDoc);
console.log('written: scripts/demo-personas.json, docs/design/demo-identities-worksheet.csv, docs/design/synthetic-social-photos.md');
