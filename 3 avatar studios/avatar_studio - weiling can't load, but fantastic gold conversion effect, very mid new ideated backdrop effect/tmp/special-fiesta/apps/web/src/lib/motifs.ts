/**
 * ADR-014 / ADR-294 / ADR-297 — decorative pixel sprites, and which of them a page may name.
 *
 * Every sprite is generated once per venue theme (`npm run motifs`), in that venue's palette.
 * They fall into two kinds, and the type system keeps them apart:
 *
 *   - GENERIC names (`SharedMotifName`): UI glyphs, sports, weather, Gameboy chrome. Any venue
 *     draws them, so a page may name them directly with `<PixelMotif name="trophy">`.
 *   - THEMED names (`ThemedMotifName`): beach and island sprites, landmarks, fauna. A venue may
 *     draw them differently or not at all, so a page never names one. It asks for a ROLE
 *     (`<RoleMotif role="bannerMark">`) and the active theme says which sprite plays it. A role
 *     may be filled by ANY sprite (ADR-298): a venue with no beach fills it with a shared one.
 *
 * `<PixelMotif name="merlion">` is therefore a compile error: the point of the split, since a
 * page that names the merlion is a page that is wrong the day the venue is not Sentosa.
 *
 * fds.md §5.5: decoration belongs to the PARTICIPANT theme only. `npm run standards` fails if
 * this module, or anything else under components/participant/, is imported from a facilitator
 * or superadmin surface.
 *
 * `wave` and `bunting` are absent on purpose: they are repeating strips used as CSS backgrounds
 * (`--motif-shoreline`, `--motif-bunting`), where their own aspect ratio is part of the rule.
 */

