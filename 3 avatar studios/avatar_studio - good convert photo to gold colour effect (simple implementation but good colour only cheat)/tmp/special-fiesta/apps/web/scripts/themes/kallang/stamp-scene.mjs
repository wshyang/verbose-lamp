#!/usr/bin/env node
/**
 * ADR-301 — stamps the committed scene files.
 *
 * The Kallang's backdrop is not drawn by a generator: it is one photographic plate,
 * imported from the owner's Kallang scene project and recompressed for the web (ADR-301).
 * It is still served immutable under `/themes/<id>/scene/` (ADR-067), so a replaced file
 * must change its URL. This hashes the files and writes
 * `src/themes/kallang/art/sceneVersion.ts`; `sceneVersion.test.ts` recomputes the hash
 * from disk and fails if the module is stale.
 *
 *   node scripts/themes/kallang/stamp-scene.mjs
 */
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const SCENE_DIR = join(ROOT, 'public', 'themes', 'kallang', 'scene');
const OUT = join(ROOT, 'src', 'themes', 'kallang', 'art', 'sceneVersion.ts');

/** The scene's files, by name. Dot entries are tooling's, not art, and are never served or hashed. */
export function sceneFiles(dir = SCENE_DIR) {
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && !entry.name.startsWith('.'))
    .map((entry) => entry.name)
    .sort();
}

/** First 8 hex digits of a hash over every file's name and bytes, in name order. */
export function sceneVersion(dir = SCENE_DIR) {
  const hash = createHash('sha256');
  for (const name of sceneFiles(dir)) {
    hash.update(name).update('\0').update(readFileSync(join(dir, name)));
  }
  return hash.digest('hex').slice(0, 8);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const version = sceneVersion();
  writeFileSync(
    OUT,
    `/**
 * Generated by scripts/themes/kallang/stamp-scene.mjs — do not edit by hand.
 *
 * Content hash of the committed scene files (ADR-067, ADR-301), appended to every scene URL so
 * a replaced file can never be served from a stale cache under its old name.
 */

export const SCENE_VERSION = '${version}';
`,
    'utf8',
  );
  console.log(`kallang scene: version ${version}`);
}
